/**
 * Level data for Geometry Jump.
 * Coordinate system: block size = 1 unit. Ground top at y = 0.
 * Player is 1x1. Positive y is up.
 *
 * Object types:
 *  - block: solid platform {x,y,w,h}
 *  - spike: floor spike (point up) {x,y} size 1x1 hitbox
 *  - spikeDown: ceiling spike {x,y}
 *  - saw: rotating hazard {x,y,r}
 *  - pad: yellow jump pad {x,y}
 *  - portal: gravity flip (optional, unused in v1)
 */

const B = (x, y, w = 1, h = 1) => ({ type: "block", x, y, w, h });
const S = (x, y = 0) => ({ type: "spike", x, y });
const SD = (x, y) => ({ type: "spikeDown", x, y });
const SAW = (x, y, r = 0.7) => ({ type: "saw", x, y, r });
const PAD = (x, y = 0) => ({ type: "pad", x, y });
const ROW = (type, startX, count, gap = 1, y = 0) =>
  Array.from({ length: count }, (_, i) =>
    type === "spike" ? S(startX + i * gap, y) : B(startX + i * gap, y)
  );

